const LABELS: Record<SocialKey, string> = {
  instagram: "Instagram",
  linkedin: "LinkedIn",
  github: "GitHub",
};

const ORDER: SocialKey[] = ["instagram", "linkedin", "github"];

export function SocialLinks() {
  const links = ORDER.map((key) => ({
    key,
    label: LABELS[key],
    href: site.socials[key],
  })).filter((l) => !l.href.includes("YOUR-"));

  if (links.length === 0) return null;

  return (
    <ul className="flex flex-wrap gap-2.5">
      {links.map((link) => (
        <li key={link.key}>
          <a
            href={link.href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`${link.label} (opens in a new tab)`}
            className="group flex size-11 items-center justify-center rounded-full border border-cream/25 text-cream/70 transition-all duration-300 hover:border-cream hover:bg-cream hover:text-ink focus-visible:border-cream motion-safe:hover:-translate-y-0.5"
          >
            <svg
              viewBox="0 0 24 24"
              aria-hidden
              focusable="false"
              fill="currentColor"
              className="size-[18px]"
            >
              {ICONS[link.key]}
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
